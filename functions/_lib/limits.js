// Потолок на размер PNG — в одном месте.
//
// Число повторялось в шести файлах (два эндпоинта, две страницы, две подсказки
// в HTML, README), и рано или поздно разъехалось бы: бэкенд отверг бы файл,
// который фронтенд посчитал допустимым. Фронтенд берёт лимит с
// `GET /api/v3/limits`, то есть и там единственный источник.
//
// 20 МБ выбрано не по одному потолку, а по трём сразу:
//
//   CatBox     — 200 МБ на файл;
//   Cloudflare — тело запроса 100 МБ на Free/Pro и 200 МБ на Business;
//   Worker     — 128 МБ памяти, причём байты копируются трижды:
//                formData() → arrayBuffer() → File для отправки в CatBox.
//
// То есть 100+ МБ упирается в память воркера ещё до ответа, и поднять потолок
// выше 20 МБ можно было бы только переездом на R2, а не правкой числа.
//
// Единственный потолок — вес файла. Ограничения по размерности нет, и это
// проверено на живых данных, а не взято из документации: из 44 плащей,
// лежащих в базе, шесть выше 4096 px по длинной стороне (максимум — стек
// 1024×29696 весом 826 КБ), и все шесть лежат на CatBox и отдаются.
//
// Раньше здесь стоял якобы существующий лимит CatBox в 4096 px, из-за
// которого в базу тащили BLOB-хранилище. Он был выдуман: первая же проверка
// показала, что сайт грузит такие капы штатно, а последняя успешная загрузка
// была за сутки до разбора. Если CatBox когда-нибудь начнёт отказывать по
// размерности, проверять надо на реальной загрузке через сайт, а не по
// догадке.
export const MAX_PNG_BYTES = 20 * 1024 * 1024;

/** Лимит в мегабайтах — для подсказок в интерфейсе и текстов ошибок. */
export const MAX_PNG_MB = MAX_PNG_BYTES / (1024 * 1024);

/** Понятное человеку сообщение вместо `413` без расшифровки. */
export function tooLargeMessage() {
  return `Файл больше ${MAX_PNG_MB} МБ`;
}
